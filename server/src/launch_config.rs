//! Writing the launch config a run is started from.
//!
//! `evolve.py --config run.toml` takes no other flag that shapes a run, so this
//! file is the *entire* interface between what a user asked for and what the
//! simulation is told. Its contract is `planet_run_schema/schema/config-v1.0.json`,
//! which this module honours as a writer: eleven keys, no more, each stating its
//! quantity in the unit its name carries.
//!
//! Two properties are worth stating because they are the reason the config exists:
//!
//! * **An undeclared key is refused, not ignored.** The schema is
//!   `additionalProperties: false` throughout, so a key this server invents stops
//!   the run instead of producing a planet that looks configured and was not.
//! * **A value that cannot be honoured is refused too.** `distance_from_star_au`
//!   is declared in the schema and consumed by no physics, so `run_config.py`
//!   accepts one value only -- see `EARTH_DISTANCE_AU` below.
//!
//! This module is below `runner`: it knows how to render and check a config file,
//! and nothing about processes, HTTP, or run directories.

use std::path::{Path, PathBuf};

use tokio::process::Command;

/// The config-schema MAJOR.MINOR this server writes.
///
/// A run refuses a MAJOR it does not share rather than launching on a file whose
/// meaning it only partly understands.
pub const CONFIG_VERSION: &str = "1.0";

/// The only orbital distance the physics can honour, in AU.
///
/// `distance_from_star_au` is a declared, inert key: nothing in `tectonics` has a
/// concept of a star, an orbit, or an albedo, and surface temperature is a
/// hardcoded constant. `run_config.py` therefore REFUSES any other value rather
/// than accepting a distance the planet never felt. Writing anything else here
/// would be this server inventing physics, which it never does.
const EARTH_DISTANCE_AU: f64 = 1.0;

/// One run's launch config, in the units the file states them in.
///
/// Conversion out of SI happens here, once, on the way to disk -- `diameter_km`
/// is the only case -- and back to SI once, in `run_config.py`, on the way in.
#[derive(Debug, Clone)]
pub struct LaunchConfig {
    /// Free text from the request, for the header comment only. Never a key.
    pub planet_name: String,
    /// The seed text the integer below was hashed from. Comment only.
    pub seed_text: String,
    pub seed: u32,
    pub steps: u64,
    pub dt_myr: f64,
    pub n_points: u32,
    pub diameter_km: f64,
    pub start_mantle_temperature_k: f64,
    pub checkpoint_every_steps: u32,
    pub run_dir: PathBuf,
    /// Relative to `run_dir`, and the stem the `run_pNNN.h5` parts are named from.
    pub output_path: PathBuf,
}

impl LaunchConfig {
    /// The file, as text.
    ///
    /// Comments carry the parameter class of every value, which is what the TOML
    /// format was chosen to allow, and name the request the file came from so a
    /// run can be traced back to what asked for it.
    pub fn to_toml(&self) -> String {
        let mut s = String::new();
        s.push_str(&format!(
            "# Launch configuration for \"{}\" (seed text \"{}\").\n",
            comment_safe(&self.planet_name),
            comment_safe(&self.seed_text)
        ));
        s.push_str(
            "#\n\
             # GENERATED by web_server, one per run. Editing it does not change the run\n\
             # that was launched from it; it only makes the record disagree with what ran.\n\
             #\n\
             # The parameter class of every value is stated, per rule 1:\n\
             #   (a) measured, published, or a given of the world being built\n\
             #   (b) a numerical choice -- resolution, time step, cadence\n\
             #   (c) a fudge -- FORBIDDEN, and there are none in this file\n\n",
        );

        s.push_str(&format!("config_version = \"{CONFIG_VERSION}\"\n\n"));

        s.push_str(
            "# (a) The integer seed the run actually receives, hashed from the request's\n\
             # seed text. Touches only the givens -- plume sites, plate seeds, initial\n\
             # ages -- so the same integer reproduces the run bit-for-bit.\n",
        );
        s.push_str(&format!("seed = {}\n\n", self.seed));

        s.push_str("# (b) Iterations to run.\n");
        s.push_str(&format!("steps = {}\n\n", self.steps));

        s.push_str(
            "# (b) Millions of years per step. Exposed so convergence can be exercised\n\
             # and a run traded against wall clock, never to tune an outcome.\n",
        );
        s.push_str(&format!("dt_myr = {}\n\n", toml_float(self.dt_myr)));

        s.push_str(
            "# (b) Points the surface cloud starts with. The cloud is an unstructured\n\
             # Voronoi tessellation, so this is a starting count, not a fixed resolution.\n",
        );
        s.push_str(&format!("n_points = {}\n\n", self.n_points));

        s.push_str(
            "# (a) A given of the world being built. Kilometres, converted from the\n\
             # metres the request states, because the key carries its unit in its name.\n",
        );
        s.push_str(&format!("diameter_km = {}\n\n", toml_float(self.diameter_km)));

        s.push_str(
            "# (a) Orbital distance. NOT a request parameter and not a choice: nothing\n\
             # in tectonics derives surface temperature from it, so the run honours this\n\
             # one value and refuses every other. Offering a knob here would be offering\n\
             # a setting the planet never feels.\n",
        );
        s.push_str(&format!(
            "distance_from_star_au = {}\n\n",
            toml_float(EARTH_DISTANCE_AU)
        ));

        s.push_str(
            "# (a) The temperature the mantle STARTS from -- the post-magma-ocean initial\n\
             # condition of the two-layer energy balance. An initial condition, not a\n\
             # target: the present-day temperature it evolves to is an outcome and has no\n\
             # key anywhere.\n",
        );
        s.push_str(&format!(
            "start_mantle_temperature_k = {}\n\n",
            toml_float(self.start_mantle_temperature_k)
        ));

        s.push_str(
            "# (b) Steps between checkpoint files; 0 writes one file for the whole run.\n\
             # A closed part is the only thing a reader may open, so this is also how far\n\
             # behind the live view runs.\n",
        );
        s.push_str(&format!(
            "checkpoint_every_steps = {}\n\n",
            self.checkpoint_every_steps
        ));

        s.push_str(
            "# The run directory: everything the run writes lives under it, and it is the\n\
             # whole interface to every reader. Absolute, because the simulation is a\n\
             # subprocess with its own working directory.\n",
        );
        s.push_str(&format!("run_dir = {}\n\n", toml_string(&self.run_dir)));

        s.push_str("# The HDF5 output, relative to run_dir.\n");
        s.push_str(&format!(
            "output_path = {}\n",
            toml_string(&self.output_path)
        ));
        s
    }
}

/// A TOML float: always with a decimal point, so `12742` cannot arrive as an
/// integer where the schema says `number` and a reader says `float`.
fn toml_float(v: f64) -> String {
    // `{:?}` on f64 is the shortest round-tripping form and keeps the `.0` that
    // `{}` drops. Non-finite values never reach here -- `PlanetParams::validate`
    // refuses them, and the env-supplied knobs are checked in `main`.
    format!("{v:?}")
}

/// A TOML basic string. Paths are data, so the quotes and backslashes in one are
/// escaped rather than assumed absent.
fn toml_string(path: &Path) -> String {
    let mut out = String::from("\"");
    for c in path.to_string_lossy().chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Free text, made safe to sit inside a `#` comment.
///
/// A newline in a planet's name would end the comment and turn whatever followed
/// into TOML, so control characters become spaces and the text is bounded.
fn comment_safe(text: &str) -> String {
    let cleaned: String = text
        .chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .take(80)
        .collect();
    cleaned.trim().to_string()
}

/// Check a written config against the schema, by running the contract's own
/// validator.
///
/// The checker is `planet_run_schema/validate_config.py` rather than a second
/// implementation of the same rules in Rust: two checkers drift, and the one that
/// matters is the one `evolve.py` is also held to. Running it before spawning
/// turns a bad config into a message here instead of a subprocess that dies
/// several seconds later with a traceback in a log file.
///
/// A validator that cannot run is reported as a failure, never skipped -- a
/// config that prints nothing because nothing checked it is the one outcome worse
/// than having no validator at all.
pub async fn validate(python: &str, schema_repo: &Path, config: &Path) -> Result<(), String> {
    let script = validator_path(schema_repo);
    if !script.exists() {
        return Err(format!(
            "the launch config could not be checked: no validator at {}. \
             Set RUN_SCHEMA to the planet_run_schema checkout.",
            script.display()
        ));
    }

    let out = Command::new(python)
        .arg(&script)
        .arg(config)
        .arg("--quiet")
        .output()
        .await
        .map_err(|e| format!("could not run {}: {e}", script.display()))?;

    if out.status.success() {
        return Ok(());
    }
    // The validator reports every violation, not the first, so all of them are
    // relayed -- one message should be enough to fix the whole file.
    let detail = String::from_utf8_lossy(&out.stdout)
        .lines()
        .chain(String::from_utf8_lossy(&out.stderr).lines())
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .collect::<Vec<_>>()
        .join("; ");
    Err(format!(
        "the launch config this server generated does not conform: {detail}"
    ))
}

/// Where the contract's validator lives inside a `planet_run_schema` checkout.
pub fn validator_path(schema_repo: &Path) -> PathBuf {
    schema_repo.join("validate_config.py")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn config() -> LaunchConfig {
        LaunchConfig {
            planet_name: "Kestrel".into(),
            seed_text: "kestrel-1".into(),
            seed: 7,
            steps: 300,
            dt_myr: 8.0,
            n_points: 500,
            diameter_km: 12_742.0,
            start_mantle_temperature_k: 2000.0,
            checkpoint_every_steps: 5,
            run_dir: PathBuf::from("/runs/job_abc"),
            output_path: PathBuf::from("parts/run.h5"),
        }
    }

    /// Every key the config file carries, and nothing else. The schema refuses an
    /// undeclared key, so a stray one here is a run that never starts.
    fn keys(toml: &str) -> Vec<String> {
        toml.lines()
            .filter(|l| !l.trim_start().starts_with('#'))
            .filter_map(|l| l.split_once('=').map(|(k, _)| k.trim().to_string()))
            .filter(|k| !k.is_empty())
            .collect()
    }

    #[test]
    fn writes_exactly_the_eleven_declared_keys() {
        let mut found = keys(&config().to_toml());
        found.sort();
        let mut expected = vec![
            "checkpoint_every_steps",
            "config_version",
            "diameter_km",
            "distance_from_star_au",
            "dt_myr",
            "n_points",
            "output_path",
            "run_dir",
            "seed",
            "start_mantle_temperature_k",
            "steps",
        ];
        expected.sort();
        assert_eq!(found, expected);
    }

    #[test]
    fn floats_keep_their_decimal_point() {
        let toml = config().to_toml();
        assert!(toml.contains("diameter_km = 12742.0"), "{toml}");
        assert!(toml.contains("dt_myr = 8.0"), "{toml}");
        assert!(toml.contains("distance_from_star_au = 1.0"), "{toml}");
        assert!(toml.contains("start_mantle_temperature_k = 2000.0"), "{toml}");
    }

    #[test]
    fn every_value_declares_a_parameter_class() {
        // Each key is preceded by a comment block, and the block that introduces
        // it states (a) or (b). Class (c) is forbidden and never written.
        let toml = config().to_toml();
        let mut class_seen = false;
        for line in toml.lines() {
            if line.starts_with("# (a)") || line.starts_with("# (b)") {
                class_seen = true;
            } else if let Some((key, _)) = line.split_once('=') {
                let key = key.trim();
                // Three keys are not parameters of the world and have no class:
                // the format's own version, and the two paths saying where the
                // run writes. The example config classes exactly the same eight.
                if matches!(key, "config_version" | "run_dir" | "output_path") {
                    continue;
                }
                assert!(class_seen, "{key} was written with no parameter class");
                class_seen = false;
            }
        }
    }

    #[test]
    fn a_name_cannot_break_out_of_its_comment() {
        let mut cfg = config();
        cfg.planet_name = "Kestrel\nsteps = 999999".into();
        let toml = cfg.to_toml();
        assert_eq!(keys(&toml).iter().filter(|k| *k == "steps").count(), 1);
        assert!(toml.contains("steps = 300"));
    }

    #[test]
    fn paths_are_escaped_rather_than_assumed_plain() {
        let mut cfg = config();
        cfg.run_dir = PathBuf::from(r#"/runs/od"d\one"#);
        assert!(cfg.to_toml().contains(r#"run_dir = "/runs/od\"d\\one""#));
    }

    /// The contract's own checker, run against a config this server wrote.
    ///
    /// Not a second implementation of the schema rules: the point is that the
    /// file passes the same validator `evolve.py` runs on read. A missing
    /// validator FAILS rather than skips -- the server refuses to launch without
    /// it, so a test that quietly passed without it would be reporting a check
    /// that never happened.
    #[tokio::test]
    async fn the_generated_config_passes_the_contracts_validator() {
        let repo = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../../planet_run_schema")
            .canonicalize()
            .expect("planet_run_schema must be checked out beside web_server");
        let python = std::env::var("PYTHON").unwrap_or_else(|_| {
            PathBuf::from(env!("CARGO_MANIFEST_DIR"))
                .join("../../venv/bin/python")
                .to_string_lossy()
                .into_owned()
        });

        let path = std::env::temp_dir().join("web_server_launch_config_test.toml");
        std::fs::write(&path, config().to_toml()).unwrap();
        validate(&python, &repo, &path).await.expect("must conform");
        let _ = std::fs::remove_file(&path);
    }
}
